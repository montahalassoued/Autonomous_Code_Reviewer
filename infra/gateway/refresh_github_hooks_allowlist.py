import ipaddress
import json
import urllib.request
from pathlib import Path


META_URL = "https://api.github.com/meta"
ALLOWLIST_PATH = Path(__file__).parent / "allowlist" / "github_hooks.conf"
REQUEST_TIMEOUT_S = 10


# GitHub's published metadata, including the "hooks" ranges its webhook deliveries come from.
def fetch_github_meta(url: str = META_URL) -> dict:
    request = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json",
                                                   "User-Agent": "autonomous-code-reviewer-gateway"})
    with urllib.request.urlopen(request, timeout=REQUEST_TIMEOUT_S) as response:
        return json.load(response)


# nginx allow lines for the hooks ranges, then deny all; every range is parsed so nothing else lands in the config.
def render_allowlist(meta: dict) -> str:
    hooks = meta.get("hooks")
    if not isinstance(hooks, list) or not hooks:
        raise ValueError("GitHub's /meta answer has no 'hooks' ranges: the allowlist was not changed")
    networks = [ipaddress.ip_network(cidr, strict=False) for cidr in hooks]
    lines = [f"# Generated by infra/gateway/refresh_github_hooks_allowlist.py from {META_URL} (hooks).",
             "# GitHub changes these ranges: rerun the script, then restart the gateway."]
    lines += [f"allow {network};" for network in networks]
    lines.append("deny all;")
    return "\n".join(lines) + "\n"


def main() -> None:
    allowlist = render_allowlist(fetch_github_meta())
    ALLOWLIST_PATH.write_text(allowlist, encoding="utf-8")
    print(f"Wrote {allowlist.count('allow ')} GitHub hooks ranges to {ALLOWLIST_PATH}")


if __name__ == "__main__":
    main()
